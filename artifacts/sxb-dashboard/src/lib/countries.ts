const BY_CODE = new Map(COUNTRIES.map((country) => [country.code, country]));

export function normalizeCountryCode(raw: unknown): string {
  if (typeof raw !== 'string') return '';
  const clean = raw.trim().toUpperCase();
  return /^[A-Z]{2}$/.test(clean) ? clean : '';
}

/** Nom traduit, ou null quand le code est absent ou inconnu. */
export function countryName(raw: unknown, language: CountryLanguage): string | null {
  const country = BY_CODE.get(normalizeCountryCode(raw));
  return country ? country[language] : null;
}

/** Drapeau en symboles indicateurs régionaux — aucune image à charger. */
export function countryFlag(raw: unknown): string {
  const code = normalizeCountryCode(raw);
  if (!code) return '';
  return String.fromCodePoint(...[...code].map((letter) => 0x1f1e6 + letter.charCodeAt(0) - 65));
}
